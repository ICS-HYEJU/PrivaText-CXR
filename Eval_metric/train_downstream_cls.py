"""
Eval_metric/train_downstream_cls.py
====================================
Trains a DenseNet-121 classifier FROM SCRATCH (weights=None -- no ImageNet or
XRV pretraining) on one real/synthetic data arm, then evaluates multi-label
CheXpert-14 AUROC on a fixed real test subsample. See feature_list.json's
`experiment-synth-utility-densenet-scratch` for the full experiment design.

This is a DIFFERENT model from Eval_metric/downstream_cls.py's XRV DenseNet --
that one is a frozen, pretrained label-agreement SCORER (no training). This
script trains its own classifier, one per data arm, to measure real-vs-synthetic
downstream training utility (the user-requested paper-style experiment).

Arms
----
  R       : real pool A only (n_real images)
  RS1100  : real pool A + synthetic counterparts of the SAME pool-A indices
  S5500   : synthetic pool B only (n_pool images)
  RS5500  : real pool A + synthetic pool B

Pool A/B and prompts come from Eval_metric/build_synth_utility_pool.py's
pool_manifest.csv.gz. Synthetic images + their pool_index come from a
--synth_dir generated by src/LDM_dp_inference.py against that pool's
label_impression.txt (descriptions.csv 'index' column == pool_index).

Usage
-----
    PYTHONPATH=<repo>/src /opt/medclip_env/bin/python Eval_metric/train_downstream_cls.py \\
        --pool_manifest data_manifests/mimic_p10_p12/synth_utility/pool_manifest.csv.gz \\
        --synth_dir EVAL/gen_out/synth_utility/eps10 --arm RS5500 \\
        --test_manifest_csv data_manifests/mimic_p10_p12/eval_subsample_test_n5000_seed42.csv.gz \\
        --root_path /storage/hjchoi/physionet.org/files/mimic-cxr/2.1.0 \\
        --device cuda:0 --out_dir EVAL/metric/synth_utility/RS5500_eps10
"""

