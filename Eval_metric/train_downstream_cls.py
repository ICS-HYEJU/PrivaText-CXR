# ── data assembly ─────────────────────────────────────────────────────────────
def _load_gen_index_pairs(gen_dir):
    """Same convention as downstream_cls.py's helper (descriptions.csv index -> file)."""
    import csv
    for base in (gen_dir, os.path.dirname(os.path.abspath(gen_dir))):
        csv_path = os.path.join(base, 'descriptions.csv')
        if os.path.isfile(csv_path):
            pairs = {}
            with open(csv_path, newline='', encoding='utf-8') as f:
                for row in csv.DictReader(f):
                    fp = os.path.join(base, row['file'])
                    if os.path.isfile(fp) and row.get('index', '').strip() != '':
                        pairs[int(row['index'])] = fp
            if pairs:
                return pairs
    raise FileNotFoundError(f'no descriptions.csv with a usable index column found under {gen_dir}')


def assemble_arm(args):
    import pandas as pd
    df = pd.read_csv(args.pool_manifest)
    label_cols = [c for c in df.columns if c not in META_COLS]
    df_a = df[df['in_pool_a']].reset_index(drop=True)
    n_real = len(df_a)

    real_items = [(r['real_image_path'], r[label_cols].to_numpy(dtype=float))
                  for _, r in df_a.iterrows()]

    items = []
    if args.arm == 'R':
        items = real_items
    else:
        synth_map = _load_gen_index_pairs(args.synth_dir)   # pool_index -> file path
        if args.arm == 'RS1100':
            wanted = set(df_a['pool_index'].tolist())
            synth_items = [(synth_map[i], df.loc[df['pool_index'] == i, label_cols].to_numpy(dtype=float)[0])
                           for i in sorted(wanted) if i in synth_map]
            items = real_items + synth_items
        elif args.arm == 'RS1100U':
            synth_items = [(fp, df.loc[df['pool_index'] == i, label_cols].to_numpy(dtype=float)[0])
                           for i, fp in sorted(synth_map.items())[:n_real]]
            items = real_items + synth_items
        elif args.arm == 'S1100':
            synth_items = [(fp, df.loc[df['pool_index'] == i, label_cols].to_numpy(dtype=float)[0])
                           for i, fp in sorted(synth_map.items())[:n_real]]
            items = synth_items
        elif args.arm == 'S5500':
            synth_items = [(fp, df.loc[df['pool_index'] == i, label_cols].to_numpy(dtype=float)[0])
                           for i, fp in sorted(synth_map.items())]
            items = synth_items
        elif args.arm == 'RS5500':
            synth_items = [(fp, df.loc[df['pool_index'] == i, label_cols].to_numpy(dtype=float)[0])
                           for i, fp in sorted(synth_map.items())]
            items = real_items + synth_items

    missing = [fp for fp, _ in items if not os.path.isfile(fp)]
    if missing:
        raise FileNotFoundError(f'{len(missing)} image path(s) in arm {args.arm} do not exist, '
                                 f'e.g. {missing[0]}')
    print(f'[arm={args.arm}] n_real_pool_A={n_real}  n_items={len(items)}  n_labels={len(label_cols)}')
    return items, label_cols


def load_test_set(args, label_cols):
    import pandas as pd
    from Eval_metric.downstream_cls import find_chexpert_csv, load_chexpert_gt
    df = pd.read_csv(args.test_manifest_csv)
    if 'dataset_split' in df.columns:
        df = df[df['dataset_split'] == 'test'].reset_index(drop=True)
    gt = load_chexpert_gt(find_chexpert_csv(args.root_path, args.chexpert_csv))
    items = []
    for _, r in df.iterrows():
        key = (int(r['subject_id']), int(r['study_id']))
        row = gt.get(key, {})
        labels = np.array([row.get(c, float('nan')) for c in label_cols], dtype=float)
        items.append((r['image_path'], labels))
    print(f'[test] n={len(items)} images from {args.test_manifest_csv}')
    return items


# ── model / loss ──────────────────────────────────────────────────────────────
class CXRClsDataset:
    def __init__(self, items, image_size, train, rotation_deg=10.0):
        self.items = items
        self.image_size = image_size
        self.train = train
        self.rotation_deg = rotation_deg

    def __len__(self):
        return len(self.items)

    def __getitem__(self, i):
        import torch
        import torchvision.transforms.functional as TF
        from Eval_metric.features import load_image_as_tensor
        fp, labels = self.items[i]
        img = load_image_as_tensor(fp, self.image_size)[0]   # [1, S, S] in [-1, 1]
        if self.train and self.rotation_deg > 0:
            angle = float(np.random.uniform(-self.rotation_deg, self.rotation_deg))
            img = TF.rotate(img, angle, fill=-1.0)
        return img, torch.from_numpy(labels).float()


def build_model(n_labels, device):
    import torch
    from torchvision.models import densenet121
    model = densenet121(weights=None, num_classes=n_labels)   # from-scratch, no ImageNet pretrain
    return model.to(device)


def compute_pos_weight(items, n_labels, clip_max=20.0):
    """Inverse-prevalence weight per label from the TRAINING pool only (0/1 rows, drop nan/-1)."""
    mat = np.stack([labels for _, labels in items])
    pw = np.ones(n_labels, dtype=np.float32)
    for j in range(n_labels):
        col = mat[:, j]
        valid = col[(col == 0.0) | (col == 1.0)]
        n_pos = int((valid == 1.0).sum())
        n_neg = int((valid == 0.0).sum())
        pw[j] = min(n_neg / n_pos, clip_max) if n_pos > 0 else 1.0
    return pw


def masked_bce_loss(logits, targets, pos_weight):
    import torch
    mask = (targets == 0.0) | (targets == 1.0)     # excludes NaN (missing) and -1 (uncertain)
    safe_targets = torch.where(mask, targets, torch.zeros_like(targets))
    loss = torch.nn.functional.binary_cross_entropy_with_logits(
        logits, safe_targets, pos_weight=pos_weight, reduction='none')
    loss = loss * mask.float()
    denom = mask.float().sum().clamp(min=1.0)
    return loss.sum() / denom


def auroc_per_label(probs, labels_raw, label_cols, min_pos=10):
    from sklearn.metrics import roc_auc_score
    per, support, curves = {}, {}, {}
    for j, c in enumerate(label_cols):
        col = labels_raw[:, j]
        mask = (col == 0.0) | (col == 1.0)
        if mask.sum() < 2:
            continue
        y_true = col[mask].astype(int)
        if len(set(y_true.tolist())) < 2:
            continue
        y_score = probs[mask, j]
        n_pos = int(y_true.sum())
        per[c] = float(roc_auc_score(y_true, y_score))
        support[c] = {'n': int(mask.sum()), 'n_pos': n_pos, 'n_neg': int(mask.sum()) - n_pos}
        curves[c] = (y_true, y_score)
    included = [c for c in per if min(support[c]['n_pos'], support[c]['n_neg']) >= min_pos]
    macro = float(np.mean([per[c] for c in included])) if included else None
    return per, macro, support, included, curves


def accuracy_metrics(probs, labels_raw, label_cols, included, threshold=0.5):
    """Masked multilabel accuracy at a fixed probability threshold.

    Missing and uncertain targets are excluded. ``macro`` uses the same reliable
    label set as macro AUROC; ``micro`` pools all known decisions. Exact match is
    computed over each row's known labels, so it remains defined when CheXpert
    contains missing/uncertain entries.
    """
    predictions = probs >= threshold
    known = (labels_raw == 0.0) | (labels_raw == 1.0)
    targets = labels_raw == 1.0
    correct = predictions == targets
    per = {}
    for j, label in enumerate(label_cols):
        mask = known[:, j]
        if mask.any():
            per[label] = float(correct[mask, j].mean())
    macro_values = [per[label] for label in included if label in per]
    row_known = known.sum(axis=1)
    valid_rows = row_known > 0
    samplewise = correct[valid_rows].astype(float) * known[valid_rows]
    samplewise = samplewise.sum(axis=1) / row_known[valid_rows]
    exact = ((correct | ~known).all(axis=1))[valid_rows]
    return {
        'threshold': float(threshold),
        'accuracy_per_label': per,
        'accuracy_macro': float(np.mean(macro_values)) if macro_values else None,
        'accuracy_micro': float(correct[known].mean()) if known.any() else None,
        'accuracy_samplewise': float(samplewise.mean()) if len(samplewise) else None,
        'accuracy_exact_match_known': float(exact.mean()) if len(exact) else None,
    }


def _plot_roc(curves, included, out_png, title):
    from sklearn.metrics import roc_curve
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    if not included:
        print('[cls] ROC plot skipped (no reliable label)')
        return
    ncols = min(4, len(included))
    nrows = (len(included) + ncols - 1) // ncols
    fig, axes = plt.subplots(nrows, ncols, figsize=(3.8 * ncols, 3.4 * nrows), squeeze=False)
    for i, c in enumerate(included):
        ax = axes[i // ncols][i % ncols]
        fpr, tpr, _ = roc_curve(*curves[c])
        ax.plot(fpr, tpr, '-', color='#dc2626')
        ax.plot([0, 1], [0, 1], ':', color='gray', lw=1)
        ax.set_title(c, fontsize=10)
        ax.set_xlabel('FPR'); ax.set_ylabel('TPR')
    for i in range(len(included), nrows * ncols):
        axes[i // ncols][i % ncols].axis('off')
    fig.suptitle(title)
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    os.makedirs(os.path.dirname(os.path.abspath(out_png)), exist_ok=True)
    fig.savefig(out_png, dpi=150)
    plt.close(fig)
    print(f'[cls] ROC -> {out_png}')


def main():
    args = parse_args()
    import torch
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    train_items, label_cols = assemble_arm(args)
    test_items = load_test_set(args, label_cols)
    n_labels = len(label_cols)

    train_ds = CXRClsDataset(train_items, args.image_size, train=True, rotation_deg=args.rotation_deg)
    test_ds = CXRClsDataset(test_items, args.image_size, train=False)
    train_loader = torch.utils.data.DataLoader(
        train_ds, batch_size=args.batch_size, shuffle=True,
        num_workers=args.num_workers, drop_last=len(train_ds) > args.batch_size)
    test_loader = torch.utils.data.DataLoader(
        test_ds, batch_size=args.batch_size, shuffle=False, num_workers=args.num_workers)

    device = args.device
    model = build_model(n_labels, device)
    pos_weight = torch.from_numpy(
        compute_pos_weight(train_items, n_labels, args.pos_weight_clip)).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)

    model.train()
    for epoch in range(1, args.epochs + 1):
        running, n_batches = 0.0, 0
        for imgs, labels in train_loader:
            imgs = imgs.repeat(1, 3, 1, 1).to(device)     # 1ch -> 3ch (plain repeat, from-scratch backbone)
            labels = labels.to(device)
            logits = model(imgs)
            loss = masked_bce_loss(logits, labels, pos_weight)
            opt.zero_grad()
            loss.backward()
            opt.step()
            running += float(loss.item())
            n_batches += 1
        print(f'[train] arm={args.arm} epoch {epoch}/{args.epochs}  loss={running / max(n_batches,1):.4f}')

    model.eval()
    all_probs, all_labels = [], []
    with torch.no_grad():
        for imgs, labels in test_loader:
            imgs = imgs.repeat(1, 3, 1, 1).to(device)
            probs = torch.sigmoid(model(imgs)).cpu().numpy()
            all_probs.append(probs)
            all_labels.append(labels.numpy())
    probs = np.concatenate(all_probs, 0)
    labels_raw = np.concatenate(all_labels, 0)

    per, macro, support, included, curves = auroc_per_label(probs, labels_raw, label_cols, args.min_pos)
    accuracy = accuracy_metrics(probs, labels_raw, label_cols, included)
    result = {
        'arm': args.arm, 'n_train': len(train_items), 'n_test': len(test_items),
        'label_cols': label_cols, 'min_pos': args.min_pos,
        'auroc_macro': macro, 'macro_labels': included,
        'auroc_per_label': per, 'support': support,
        **accuracy,
    }
    os.makedirs(args.out_dir, exist_ok=True)
    with open(os.path.join(args.out_dir, 'eval_summary.json'), 'w') as f:
        json.dump(result, f, indent=2)
    _plot_roc(curves, included, os.path.join(args.out_dir, 'roc.png'),
              f'Downstream AUROC (from-scratch DenseNet-121) -- arm={args.arm}')
    if args.save_ckpt:
        torch.save(model.state_dict(), os.path.join(args.out_dir, 'model.pt'))

    macro_str = f'{macro:.4f}' if macro is not None else 'NA'
    print(f'[result] arm={args.arm}  n_train={len(train_items)}  auroc_macro={macro_str}  '
          f'over {len(included)}/{n_labels} labels (min_pos={args.min_pos})')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
