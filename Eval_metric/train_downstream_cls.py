META_COLS = {'pool_index', 'in_pool_a', 'ds_index', 'subject_id', 'study_id',
             'real_image_path', 'prompt_text'}


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--pool_manifest', required=True)
    p.add_argument('--synth_dir', default=None,
                   help='required for arms RS1100/S5500/RS5500')
    p.add_argument('--arm', required=True,
                   choices=['R', 'RS1100', 'RS1100U', 'S1100', 'S5500', 'RS5500'])
    p.add_argument('--test_manifest_csv', required=True,
                   help='manifest-schema csv(.gz) with image_path,subject_id,study_id '
                        '(e.g. eval_subsample_test_n5000_seed42.csv.gz)')
    p.add_argument('--root_path', required=True, help='MIMIC root (CheXpert csv fallback)')
    p.add_argument('--chexpert_csv', default=None)
    p.add_argument('--device', default='cuda:0')
    p.add_argument('--epochs', default=30, type=int)
    p.add_argument('--batch_size', default=32, type=int)
    p.add_argument('--lr', default=1e-4, type=float)
    p.add_argument('--weight_decay', default=1e-4, type=float)
    p.add_argument('--seed', default=42, type=int)
    p.add_argument('--image_size', default=224, type=int)
    p.add_argument('--min_pos', default=10, type=int)
    p.add_argument('--pos_weight_clip', default=20.0, type=float)
    p.add_argument('--rotation_deg', default=10.0, type=float)
    p.add_argument('--num_workers', default=4, type=int)
    p.add_argument('--out_dir', required=True)
    p.add_argument('--save_ckpt', action='store_true', help='persist the trained weights (default: metrics only)')
